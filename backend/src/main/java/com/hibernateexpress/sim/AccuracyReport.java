package com.hibernateexpress.sim;

import com.hibernateexpress.sim.AccuracySimulation.Metric;
import com.hibernateexpress.sim.AccuracySimulation.Scenario;
import com.hibernateexpress.sim.AccuracySimulation.Summary;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/** Runs every accuracy scenario and writes the results as a Markdown report. */
public final class AccuracyReport {

  private AccuracyReport() {}

  public static List<Summary> runAll() {
    List<Summary> out = new ArrayList<>();
    for (Scenario sc : AccuracySimulation.distanceScenarios()) out.add(AccuracySimulation.run(sc));
    for (Scenario sc : AccuracySimulation.timeScenarios()) out.add(AccuracySimulation.run(sc));
    return out;
  }

  public static String markdown(List<Summary> summaries) {
    StringBuilder sb = new StringBuilder();
    sb.append("# Alarm accuracy report\n\n")
        .append("Generated by `java -jar hibernate-express.jar accuracy` (Java backend, ")
        .append("`com.hibernateexpress.sim.AccuracySimulation`). Each row simulates many rides with\n")
        .append("Gaussian GPS noise on a real OSRM road route (Hyderabad MGBS → Hanamkonda, 143 km) or a\n")
        .append("synthetic edge case, feeding fixes into the same `TripEngine` the server runs for real trips.\n\n")
        .append("**Error = where the alarm actually rang minus where it should ring.** Positive means it rang\n")
        .append("early (you get a little extra time), negative means late.\n\n")
        .append("| Scenario | Rides | Rang | Target | Median error | 5th–95th percentile | Worst late | Notes |\n")
        .append("|---|---:|---:|---:|---:|---:|---:|---|\n");
    for (Summary s : summaries) {
      Scenario sc = s.scenario();
      String unit = sc.metric() == Metric.METRES ? "m" : "s";
      String target =
          sc.metric() == Metric.METRES
              ? fmt(sc.distanceM() / 1000.0) + " km left"
              : sc.timeMin() + " min left";
      sb.append(String.format(
          Locale.ROOT,
          "| %s | %d | %d/%d | %s | %s | %s … %s | %s | %s |%n",
          sc.name(),
          sc.rides(),
          s.fired(),
          sc.rides(),
          target,
          signed(s.percentile(0.5), unit),
          signed(s.percentile(0.05), unit),
          signed(s.percentile(0.95), unit),
          s.worstLate() == 0 ? "never late" : signed(s.worstLate(), unit),
          sc.note()));
    }
    sb.append("\nHow to read it: with a fix every second the alarm rings within a few tens of metres of the\n")
        .append("chosen point. Between fixes the engine keeps counting down at the measured pace, so sparse\n")
        .append("GPS (every 5–15 s) costs little. Time-based alarms use the measured pace of the bus, so a bus\n")
        .append("that slows down near the stop gets woken up early rather than late.\n");
    return sb.toString();
  }

  public static void write(Path file) throws IOException {
    List<Summary> summaries = runAll();
    String md = markdown(summaries);
    if (file.getParent() != null) Files.createDirectories(file.getParent());
    Files.writeString(file, md, StandardCharsets.UTF_8);
    System.out.println(md);
    System.out.println("Wrote " + file.toAbsolutePath().normalize());
  }

  private static String signed(double v, String unit) {
    if (!Double.isFinite(v)) return "—";
    long r = Math.round(v);
    return (r > 0 ? "+" : "") + r + " " + unit;
  }

  private static String fmt(double v) {
    return v == Math.rint(v) ? String.valueOf((long) v) : String.format(Locale.ROOT, "%.1f", v);
  }
}
